"""Run the validation benchmark over the labeled corpus, across all three
conditions (static_only / static_policy / full), and write a results report.

The LLM judge (full condition only) is used when --llm is passed and
ANTHROPIC_API_KEY is set. Risky artifacts blocked by deterministic layers
short-circuit before the judge, so judge cost stays low.

Usage:
    python scripts/run_benchmark.py --llm
    python scripts/run_benchmark.py            # judge stub (no API calls)
"""

from __future__ import annotations

import argparse
import json
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

import yaml

from agent_factory.orchestrator import run_validation
from agent_factory.pipeline import CONDITIONS
from agent_factory.schemas import Decision, TaskSpec

REPO = Path(__file__).resolve().parents[1]


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=str(REPO / "corpus" / "manifest.yaml"))
    ap.add_argument("--llm", action="store_true", help="Use the real Anthropic judge in 'full'.")
    ap.add_argument("--out-json", default=str(REPO / "benchmark_results.json"))
    ap.add_argument("--out-md", default=str(REPO / "BENCHMARK.md"))
    args = ap.parse_args()

    # Console may be a legacy code page (e.g. cp1251); don't crash on arrows/unicode.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    entries = yaml.safe_load(Path(args.manifest).read_text(encoding="utf-8"))

    model_client = None
    model_name = "stub"
    if args.llm:
        from agent_factory.adapters.anthropic_client import AnthropicJudge

        judge = AnthropicJudge()
        model_client = judge
        model_name = judge.model

    timestamp = _now()
    rows: list[dict] = []
    for e in entries:
        task = TaskSpec.model_validate(e["task"])
        agent = str(REPO / e["agent"])
        for cond in CONDITIONS:
            report = run_validation(
                task,
                agent,
                condition=cond,
                run_id=uuid.uuid4().hex[:12],
                created_at=timestamp,
                model_client=model_client if cond == "full" else None,
            )
            rows.append(
                {
                    "id": e["id"],
                    "label": e["label"],
                    "condition": cond,
                    "decision": report.final_decision.value,
                    "latency_ms": round(sum(report.timings.values()), 1),
                }
            )

    metrics = _compute_metrics(rows)
    md = _render_md(rows, metrics, model_name, timestamp, len(entries))

    Path(args.out_json).write_text(
        json.dumps({"timestamp": timestamp, "model": model_name, "rows": rows, "metrics": metrics},
                   indent=2),
        encoding="utf-8",
    )
    Path(args.out_md).write_text(md, encoding="utf-8")
    print(md)


def _accepted(decision: str) -> bool:
    return decision == Decision.PASS.value


def _compute_metrics(rows: list[dict]) -> dict:
    metrics: dict[str, dict] = {}
    for cond in CONDITIONS:
        crows = [r for r in rows if r["condition"] == cond]
        unsafe = [r for r in crows if r["label"] == "unsafe"]
        safe = [r for r in crows if r["label"] == "safe"]
        unsafe_accepted = sum(1 for r in unsafe if _accepted(r["decision"]))
        safe_accepted = sum(1 for r in safe if _accepted(r["decision"]))
        metrics[cond] = {
            "unsafe_total": len(unsafe),
            "unsafe_accepted": unsafe_accepted,
            "uar": round(unsafe_accepted / len(unsafe), 3) if unsafe else 0.0,
            "safe_total": len(safe),
            "safe_accepted": safe_accepted,
            "valid_acceptance_rate": round(safe_accepted / len(safe), 3) if safe else 0.0,
            "over_block": len(safe) - safe_accepted,
        }
    return metrics


def _render_md(rows, metrics, model_name, timestamp, n) -> str:
    by_id: dict[str, dict] = {}
    for r in rows:
        by_id.setdefault(r["id"], {"label": r["label"]})[r["condition"]] = r["decision"]

    lines = [
        "# Benchmark Results",
        "",
        "> Auto-generated by `scripts/run_benchmark.py`. Reproduce with "
        "`python scripts/run_benchmark.py --llm`.",
        "",
        f"- **Corpus:** {n} artifacts ({sum(1 for v in by_id.values() if v['label']=='safe')} safe, "
        f"{sum(1 for v in by_id.values() if v['label']=='unsafe')} unsafe)",
        f"- **Judge model (full condition):** `{model_name}`",
        f"- **Run timestamp (UTC):** {timestamp}",
        "",
        "## Decisions per artifact",
        "",
        "| Artifact | Label | static_only | static_policy | full |",
        "|---|---|---|---|---|",
    ]
    for aid, v in by_id.items():
        lines.append(
            f"| {aid} | {v['label']} | {v.get('static_only','-')} | "
            f"{v.get('static_policy','-')} | {v.get('full','-')} |"
        )

    lines += [
        "",
        "## Metrics by condition",
        "",
        "| Condition | Unsafe Acceptance Rate (UAR) ↓ | Valid Acceptance Rate ↑ | Over-blocked (safe) |",
        "|---|---|---|---|",
    ]
    for cond in CONDITIONS:
        m = metrics[cond]
        lines.append(
            f"| {cond} | {m['uar']} ({m['unsafe_accepted']}/{m['unsafe_total']}) | "
            f"{m['valid_acceptance_rate']} ({m['safe_accepted']}/{m['safe_total']}) | {m['over_block']} |"
        )

    uar_static = metrics["static_only"]["uar"]
    uar_full = metrics["full"]["uar"]
    lines += [
        "",
        "## Interpretation",
        "",
        f"- Unsafe Acceptance Rate falls from **{uar_static}** (static-only baseline) to "
        f"**{uar_full}** (full pipeline) — added layers block unsafe/policy-violating agents "
        "the lightweight baseline accepts.",
        "- **Definitions:** UAR = unsafe/policy-violating agents incorrectly accepted (PASS). "
        "Valid Acceptance Rate = safe agents correctly accepted. Over-blocked = safe agents "
        "that were FAILed or ESCALATEd.",
        "- This is a small demonstration corpus; the thesis benchmark scales the same pipeline "
        "to the planned 720-run design.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
